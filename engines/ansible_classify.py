"""Keyword-based classification engine for Ansible error summaries.

Generated by: drift (manual rules from upstream prompt keyword guidelines)
Replaces: LLM classify step in ansible-log-analysis pipeline
Accuracy target: 100% on 500-log corpus (keyword rules cover all 8 categories)
"""

import json
import re


CATEGORY_RULES = [
    (
        re.compile(r"ec2|cloudformation|aws[_ ]access|vpc|iam.{0,5}role|bastion|aws|ami|instance.type|boto|security.group", re.I),
        "Cloud Infrastructure / AWS Engineers",
    ),
    (
        re.compile(r"cluster|operator|olm|pod|rbac|serviceaccount|openshift|kube|crd|api.?server|etcd|node.?not.?ready", re.I),
        "Kubernetes Cluster Admins",
    ),
    (
        re.compile(r"ansible|playbook|runner|role|variable.*undefined|undefined.*variable|task.*include|jinja|template|vault|collection|galaxy", re.I),
        "DevOps / CI/CD Engineers (Ansible + Automation Platform)",
    ),
    (
        re.compile(r"ssh|dns|certificate|tls|cert.?manager|firewall|hostname|resolve|unreachable|connection.refused|port.22", re.I),
        "Networking / Security Engineers",
    ),
    (
        re.compile(r"subscription|repository|yum|dnf|package|registration|rpm|rhel|rhsm|satellite|repos", re.I),
        "System Administrators / OS Engineers",
    ),
    (
        re.compile(r"gitea|argocd|helm|tssc|deployment.*failed|pipeline|tekton|quay|registry", re.I),
        "Application Developers / GitOps / Platform Engineers",
    ),
    (
        re.compile(r"azure.{0,5}ad|sso|authentication|token.*expired|login|federation|oauth|identity|saml|ldap", re.I),
        "Identity & Access Management (IAM) Engineers",
    ),
]

DEFAULT_CATEGORY = "Other / Miscellaneous"


def process(input_text: str, llm=None) -> dict:
    """Classify an Ansible error summary using keyword rules.

    Args:
        input_text: Error summary text (output from summarize step)
        llm: Unused — classification is fully deterministic

    Returns:
        dict with 'category' key
    """
    best_category = DEFAULT_CATEGORY
    best_score = 0

    for pattern, category in CATEGORY_RULES:
        matches = pattern.findall(input_text)
        if len(matches) > best_score:
            best_score = len(matches)
            best_category = category

    return {"category": best_category}


if __name__ == "__main__":
    import sys
    if len(sys.argv) < 2:
        print("Usage: python ansible_classify.py <input_file>")
        sys.exit(1)
    input_text = open(sys.argv[1]).read()
    result = process(input_text)
    print(json.dumps(result, indent=2))
