"""Signal-presence routing engine for Ansible error summaries.

Generated by: drift (manual rules from upstream prompt decision criteria)
Replaces: LLM route step in ansible-log-analysis pipeline
Accuracy target: >=95% on 500-log corpus
"""

import json
import re


# Signals indicating the error is self-contained and actionable
# These match against processed summaries (not raw logs)
SUFFICIENT_SIGNALS = [
    re.compile(r"(undefined variable|permission|forbidden|timeout|connection refused|not found|no such)", re.I),
    re.compile(r"(error|failed|failure|cannot|denied|refused|unable)", re.I),
    re.compile(r"(line \d+|column \d+|code \d{3}|rc=[1-9])", re.I),
    re.compile(r"(namespace|resource|cluster|host|node|service|role|task)", re.I),
    re.compile(r"(dns|ssh|certificate|tls|aws|ec2|subscription|repository)", re.I),
]

# Signals indicating insufficient information
INSUFFICIENT_SIGNALS = [
    re.compile(r"(no_log|censored|REDACTED)", re.I),
    re.compile(r"empty log", re.I),
    re.compile(r"^$"),
]


def process(input_text: str, llm=None) -> dict:
    """Route an error summary based on signal completeness.

    Args:
        input_text: Error summary + category (output from summarize + classify)
        llm: Unused — routing is fully deterministic

    Returns:
        dict with 'suggestion' key
    """
    if not input_text or not input_text.strip():
        return {"suggestion": "Need More Context"}

    # Check for insufficient signals first
    for pattern in INSUFFICIENT_SIGNALS:
        if pattern.search(input_text):
            return {"suggestion": "Need More Context"}

    # Count sufficient signals
    signal_count = sum(1 for p in SUFFICIENT_SIGNALS if p.search(input_text))

    # Need at least 2 positive signals for confidence
    if signal_count >= 2:
        return {"suggestion": "No More Context Needed"}

    # Default: need more context for ambiguous cases
    return {"suggestion": "Need More Context"}


if __name__ == "__main__":
    import sys
    if len(sys.argv) < 2:
        print("Usage: python ansible_route.py <input_file>")
        sys.exit(1)
    input_text = open(sys.argv[1]).read()
    result = process(input_text)
    print(json.dumps(result, indent=2))
