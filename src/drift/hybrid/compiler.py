"""Compile a hybrid spec + prompt into a standalone Python engine.

Takes a hybrid.yaml (rules + llm_fields) and a system prompt, and generates
a self-contained Python module with a process(input_text, llm) function.
"""

from __future__ import annotations

import re
import textwrap
from datetime import datetime, timezone


def compile_engine(
    rules: list[dict],
    llm_fields: list[str],
    system_prompt: str,
    engine_name: str = "engine",
) -> str:
    """Generate a Python module from a hybrid spec.

    Args:
        rules: Rule definitions from hybrid.yaml
        llm_fields: Fields that require LLM inference
        system_prompt: System prompt for LLM calls
        engine_name: Name for the generated module

    Returns:
        Complete Python source code as a string
    """
    # Separate rules by type
    regex_rules = [r for r in rules if r["type"] == "regex"]
    regex_all_rules = [r for r in rules if r["type"] == "regex_all"]
    literal_rules = [r for r in rules if r["type"] == "literal"]
    mapping_rules = [r for r in rules if r["type"] == "mapping"]
    conditional_rules = [r for r in rules if r["type"] == "conditional"]

    tier1_count = len(regex_rules) + len(regex_all_rules) + len(literal_rules)
    tier2_count = len(mapping_rules) + len(conditional_rules)

    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines = []

    # Module docstring
    lines.append(f'"""Auto-generated processing engine: {engine_name}')
    lines.append(f"")
    lines.append(f"Generated by: drift compile")
    lines.append(f"Generated at: {timestamp}")
    lines.append(f"Tier 1 (regex/literal): {tier1_count} fields")
    lines.append(f"Tier 2 (mapping/conditional): {tier2_count} fields")
    lines.append(f"Tier 3 (LLM): {len(llm_fields)} field groups")
    lines.append(f'"""')
    lines.append(f"")
    lines.append(f"import json")
    lines.append(f"import re")
    lines.append(f"")
    lines.append(f"")

    # System prompt as a constant
    lines.append(f"SYSTEM_PROMPT = {_quote_multiline(system_prompt)}")
    lines.append(f"")
    lines.append(f"LLM_FIELDS = {llm_fields!r}")
    lines.append(f"")
    lines.append(f"")

    # --- process() function ---
    lines.append(f"def process(input_text: str, llm=None) -> dict:")
    lines.append(f'    """Process input and return structured output.')
    lines.append(f"")
    lines.append(f"    Args:")
    lines.append(f"        input_text: Raw input text to process")
    lines.append(f"        llm: Optional async LLM provider with .complete(system, prompt, temperature=0)")
    lines.append(f"              If None, only Tier 1 and Tier 2 fields are returned.")
    lines.append(f"")
    lines.append(f"    Returns:")
    lines.append(f"        dict with all extracted, computed, and LLM-generated fields")
    lines.append(f'    """')
    lines.append(f"    result = {{}}")
    lines.append(f"")

    # Tier 1: regex extraction
    if regex_rules or regex_all_rules or literal_rules:
        lines.append(f"    # --- Tier 1: Deterministic extraction (< 1ms) ---")
        for rule in regex_rules:
            path = rule["path"]
            pattern = rule["pattern"]
            lines.append(f"    _set(result, {path!r}, _extract({_emit_pattern(pattern)}, input_text))")
        for rule in regex_all_rules:
            path = rule["path"]
            pattern = rule["pattern"]
            lines.append(f"    _set(result, {path!r}, _extract_all({_emit_pattern(pattern)}, input_text))")
        for rule in literal_rules:
            path = rule["path"]
            value = rule["value"]
            lines.append(f"    _set(result, {path!r}, {value!r})")
        lines.append(f"")

    # Tier 2: mapping rules
    for rule in mapping_rules:
        path = rule["path"]
        source = rule["source"]
        mapping = rule["map"]
        default = rule.get("default")
        lines.append(f"    # --- Tier 2: Mapping {path} ---")
        lines.append(f"    _source = _get(result, {source!r})")
        lines.append(f"    _map = {mapping!r}")
        if default is not None:
            lines.append(f"    _set(result, {path!r}, _map.get(str(_source), {default!r}))")
        else:
            lines.append(f"    _mapped = _map.get(str(_source))")
            lines.append(f"    if _mapped is not None:")
            lines.append(f"        _set(result, {path!r}, _mapped)")
        lines.append(f"")

    # Tier 2: conditional rules
    for rule in conditional_rules:
        path = rule["path"]
        conditions = rule.get("conditions", [])
        default = rule.get("default")
        lines.append(f"    # --- Tier 2: Conditional {path} ---")
        for i, cond in enumerate(conditions):
            when = cond["when"]
            value = cond["value"]
            keyword = "if" if i == 0 else "elif"
            checks = " and ".join(
                f"_get(result, {field!r}) == {expected!r}"
                for field, expected in when.items()
            )
            lines.append(f"    {keyword} {checks}:")
            lines.append(f"        _set(result, {path!r}, {value!r})")
        if default is not None:
            lines.append(f"    else:")
            lines.append(f"        _set(result, {path!r}, {default!r})")
        lines.append(f"")

    # Tier 3: LLM call
    if llm_fields:
        lines.append(f"    # --- Tier 3: LLM for reasoning fields ---")
        lines.append(f"    if llm:")
        lines.append(f"        _llm_result = _call_llm(llm, input_text, result)")
        lines.append(f"        _merge(result, _llm_result)")
        lines.append(f"")

    lines.append(f"    return result")
    lines.append(f"")
    lines.append(f"")

    # --- Helper functions ---

    # _extract
    lines.append(f"def _extract(pattern: str, text: str) -> str | None:")
    lines.append(f'    """Extract first regex capture group."""')
    lines.append(f"    m = re.search(pattern, text, re.MULTILINE)")
    lines.append(f"    return m.group(1).strip() if m else None")
    lines.append(f"")
    lines.append(f"")

    # _extract_all
    if regex_all_rules:
        lines.append(f"def _extract_all(pattern: str, text: str) -> list[str] | None:")
        lines.append(f'    """Extract all regex matches."""')
        lines.append(f"    matches = re.findall(pattern, text, re.MULTILINE)")
        lines.append(f"    return matches if matches else None")
        lines.append(f"")
        lines.append(f"")

    # _set
    lines.append(f"def _set(obj: dict, path: str, value) -> None:")
    lines.append(f'    """Set a value in a nested dict using dot notation."""')
    lines.append(f"    if value is None:")
    lines.append(f"        return")
    lines.append(f"    keys = path.split('.')")
    lines.append(f"    for key in keys[:-1]:")
    lines.append(f"        obj = obj.setdefault(key, {{}})")
    lines.append(f"    obj[keys[-1]] = value")
    lines.append(f"")
    lines.append(f"")

    # _get
    lines.append(f"def _get(obj: dict, path: str):")
    lines.append(f'    """Get a value from a nested dict using dot notation."""')
    lines.append(f"    for key in path.split('.'):")
    lines.append(f"        if isinstance(obj, dict):")
    lines.append(f"            obj = obj.get(key)")
    lines.append(f"        else:")
    lines.append(f"            return None")
    lines.append(f"    return obj")
    lines.append(f"")
    lines.append(f"")

    # _merge
    if llm_fields:
        lines.append(f"def _merge(base: dict, overlay: dict) -> None:")
        lines.append(f'    """Deep-merge overlay into base, overlay wins conflicts."""')
        lines.append(f"    for key, val in overlay.items():")
        lines.append(f"        if key in base and isinstance(base[key], dict) and isinstance(val, dict):")
        lines.append(f"            _merge(base[key], val)")
        lines.append(f"        else:")
        lines.append(f"            base[key] = val")
        lines.append(f"")
        lines.append(f"")

        # _call_llm
        lines.append(f"def _call_llm(llm, input_text: str, extracted: dict) -> dict:")
        lines.append(f'    """Call LLM for reasoning fields only."""')
        lines.append(f"    fields_str = ', '.join(LLM_FIELDS)")
        lines.append(f"    extracted_json = json.dumps(extracted, indent=2)")
        lines.append(f"    prompt = (")
        lines.append(f'        "The following fields have already been extracted:\\n"')
        lines.append(f'        f"```json\\n{{extracted_json}}\\n```\\n\\n"')
        lines.append(f'        "Based on the input below, provide ONLY these fields as valid JSON:\\n"')
        lines.append(f'        f"{{fields_str}}\\n\\n"')
        lines.append(f'        "Do not repeat already-extracted fields. Output valid JSON only.\\n\\n"')
        lines.append(f'        f"{{input_text}}"')
        lines.append(f"    )")
        lines.append(f"    import asyncio")
        lines.append(f"    response = asyncio.get_event_loop().run_until_complete(")
        lines.append(f"        llm.complete(SYSTEM_PROMPT, prompt, temperature=0)")
        lines.append(f"    )")
        lines.append(f"    return _parse_json(response.content)")
        lines.append(f"")
        lines.append(f"")

        # _parse_json
        lines.append(f"def _parse_json(text: str) -> dict:")
        lines.append(f'    """Parse JSON from LLM response, handling code fences."""')
        lines.append(f"    text = text.strip()")
        lines.append(f'    if text.startswith("```"):')
        lines.append(f'        lines = text.split("\\n")')
        lines.append(f"        lines = lines[1:]")
        lines.append(f'        if lines and lines[-1].strip() == "```":')
        lines.append(f"            lines = lines[:-1]")
        lines.append(f'        text = "\\n".join(lines)')
        lines.append(f"    try:")
        lines.append(f"        return json.loads(text)")
        lines.append(f"    except json.JSONDecodeError:")
        lines.append(f'        return {{"_raw": text}}')
        lines.append(f"")
        lines.append(f"")

    # --- main block for standalone testing ---
    lines.append(f'if __name__ == "__main__":')
    lines.append(f"    import sys")
    lines.append(f"    if len(sys.argv) < 2:")
    lines.append(f'        print("Usage: python {engine_name}.py <input_file>")')
    lines.append(f"        sys.exit(1)")
    lines.append(f"    input_text = open(sys.argv[1]).read()")
    lines.append(f"    result = process(input_text)")
    lines.append(f"    print(json.dumps(result, indent=2))")
    lines.append(f"")

    return "\n".join(lines)


def _quote_multiline(s: str) -> str:
    """Quote a multiline string as a Python triple-quoted string."""
    escaped = s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return f'"""\\\n{escaped}"""'


def _emit_pattern(pattern: str) -> str:
    """Emit a regex pattern as a valid Python string literal.

    Patterns from YAML are already valid regex (e.g., \\s* means regex \\s*).
    We need to produce a Python string that, when interpreted, gives the same regex.
    Using repr() would double-escape. Instead, use a raw string if possible,
    otherwise fall back to repr().
    """
    # Raw strings can't end with an odd number of backslashes or contain the quote char
    if "'" not in pattern and not pattern.endswith("\\"):
        return f"r'{pattern}'"
    if '"' not in pattern and not pattern.endswith("\\"):
        return f'r"{pattern}"'
    # Fallback: regular string with proper escaping
    return repr(pattern)
